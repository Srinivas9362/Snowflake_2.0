⭐ SECTION 7 — FILE FORMATS IN SNOWflake (Deep Explanation)

Snowflake supports multiple data formats:
| File Format | Type             | Use Case                      |
| ----------- | ---------------- | ----------------------------- |
| **CSV**     | Text             | Traditional ETL, flat files   |
| **JSON**    | Semi-structured  | API ingest, logs              |
| **Parquet** | Columnar         | Big data, optimized analytics |
| **Avro**    | Row-based binary | Streaming (Kafka)             |
| **ORC**     | Columnar         | Hadoop ecosystem              |
| **XML**     | Semi-structured  | Legacy enterprise systems     |
